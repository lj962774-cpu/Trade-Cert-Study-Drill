// 류 code → 부(Section) 로마숫자 매핑 (HS 표준 구간)
function secOf(code) {
  const n = parseInt(code, 10);
  if (n <= 5) return 'I';
  if (n <= 14) return 'II';
  if (n === 15) return 'III';
  if (n <= 24) return 'IV';
  if (n <= 27) return 'V';
  if (n <= 38) return 'VI';
  if (n <= 40) return 'VII';
  if (n <= 43) return 'VIII';
  if (n <= 46) return 'IX';
  if (n <= 49) return 'X';
  if (n <= 63) return 'XI';
  if (n <= 67) return 'XII';
  if (n <= 70) return 'XIII';
  if (n === 71) return 'XIV';
  if (n <= 83) return 'XV';
  if (n <= 85) return 'XVI';
  if (n <= 89) return 'XVII';
  if (n <= 92) return 'XVIII';
  if (n === 93) return 'XIX';
  if (n <= 96) return 'XX';
  return 'XXI';
}

